/**
 * توحيد إجابة سؤال الأمان قبل المقارنة — نفس normalizeAnswer() بالحرف من
 * prototype/screens/auth/00-first-run-setup.html.
 *
 * ⚠ لازم الباك يطبّق نفس الدالة بالظبط على النص قبل عمل الـ hash — مش على
 * اللي المستخدم كتبه بالحرف — وإلا طبيب كتب «أحمد» واسترجع بـ«احمد» بعد
 * سنة هيتقفل برّه حسابه للأبد (مفيش سيرفر ولا إيميل استرجاع في النظام).
 */
export function normalizeAnswer(value: string): string {
  return (value || '')
    .replace(/[ً-ْـ]/g, '') // تشكيل + تطويل
    .replace(/[أإآٱ]/g, 'ا') // كل أشكال الألف
    .replace(/ة/g, 'ه') // تاء مربوطة ← هاء
    .replace(/[ىئ]/g, 'ي') // ألف مقصورة + ياء همزة ← ياء
    .replace(/ؤ/g, 'و')
    .replace(/[٠-٩]/g, (d) => String('٠١٢٣٤٥٦٧٨٩'.indexOf(d))) // أرقام هندية ← لاتينية
    .replace(/\s+/g, ' ') // مسافات متكررة
    .trim()
    .toLowerCase(); // حالة الأحرف اللاتينية
}
